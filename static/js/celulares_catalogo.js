window.FALLBACK_CAPACIDADES = ["64GB", "128GB", "256GB", "512GB", "1TB", "8GB / 128GB", "8GB / 256GB", "12GB / 256GB"];
window.FALLBACK_COLORES = ["Negro", "Blanco", "Plata", "Natural", "Desierto", "Azul", "Naranja", "Oro", "Morado", "Rosa", "Verde", "Rojo"];

window.initSelectorCelular = function (prefix, defaults = {}) {
    const marcaSel = document.getElementById(`${prefix}_marca_select`);
    const marcaCustom = document.getElementById(`${prefix}_marca_custom`);
    const modeloSel = document.getElementById(`${prefix}_modelo_select`);
    const modeloCustom = document.getElementById(`${prefix}_modelo_custom`);
    const memSel = document.getElementById(`${prefix}_memoria_select`);
    const colSel = document.getElementById(`${prefix}_color_select`);

    if (!marcaSel || !modeloSel) return;

    const marcasList = Object.keys(window.CATALOGO_CELULARES);
    let marcaHtml = `<option value="">-- Seleccione Marca --</option>`;
    marcasList.forEach(m => {
        marcaHtml += `<option value="${m}">${m}</option>`;
    });
    marcaHtml += `<option value="__otra__">➕ Agregar otra marca...</option>`;
    marcaSel.innerHTML = marcaHtml;

    function resetCapacidadYColor() {
        if (memSel && memSel.tagName === 'SELECT') {
            memSel.innerHTML = `<option value="">-- Primero elija Referencia --</option>`;
        }
        if (colSel && colSel.tagName === 'SELECT') {
            colSel.innerHTML = `<option value="">-- Primero elija Referencia --</option>`;
        }
    }

    function actualizarEspecificacionesDeReferencia(marca, modelo, memPre = '', colPre = '') {
        let caps = [];
        let cols = [];

        if (marca && modelo && window.CATALOGO_CELULARES[marca] && window.CATALOGO_CELULARES[marca][modelo]) {
            caps = window.CATALOGO_CELULARES[marca][modelo].capacidades || [];
            cols = window.CATALOGO_CELULARES[marca][modelo].colores || [];
        } else if (marca === '__otra__' || modelo === '__otro__') {
            caps = window.FALLBACK_CAPACIDADES;
            cols = window.FALLBACK_COLORES;
        } else {
            resetCapacidadYColor();
            return;
        }

        if (memSel && memSel.tagName === 'SELECT') {
            let memHtml = `<option value="">-- Seleccionar Capacidad --</option>`;
            if (prefix === 'masivo') {
                memHtml += `<option value="TODAS">📋 Todas las capacidades</option>`;
            }
            caps.forEach(c => {
                memHtml += `<option value="${c}">${c}</option>`;
            });
            if (memPre && !caps.includes(memPre)) {
                memHtml += `<option value="${memPre}">${memPre}</option>`;
            }
            memHtml += `<option value="__otra_cap__">➕ Otra capacidad...</option>`;
            memSel.innerHTML = memHtml;
            if (memPre) {
                memSel.value = memPre;
            } else if (caps.length === 1 && prefix !== 'masivo') {
                memSel.value = caps[0];
            }
        }

        if (colSel && colSel.tagName === 'SELECT') {
            let colHtml = `<option value="">-- Seleccionar Color --</option>`;
            if (prefix === 'masivo' || prefix === 'imgref') {
                colHtml += `<option value="TODOS">🎨 Todos los colores</option>`;
            }
            cols.forEach(c => {
                colHtml += `<option value="${c}">${c}</option>`;
            });
            if (colPre && !cols.includes(colPre)) {
                colHtml += `<option value="${colPre}">${colPre}</option>`;
            }
            colHtml += `<option value="__otro_col__">➕ Otro color...</option>`;
            colSel.innerHTML = colHtml;
            if (colPre) {
                colSel.value = colPre;
            } else if (cols.length === 1 && prefix !== 'masivo' && prefix !== 'imgref') {
                colSel.value = cols[0];
            }
        }
    }

    if (memSel && memSel.tagName === 'SELECT') {
        memSel.addEventListener('change', function () {
            if (this.value === '__otra_cap__') {
                const nuevaCap = prompt('Escribe la capacidad / RAM (Ej: 256GB o 8GB / 256GB):');
                if (nuevaCap && nuevaCap.trim()) {
                    const val = nuevaCap.trim();
                    const opt = document.createElement('option');
                    opt.value = val;
                    opt.textContent = val;
                    this.insertBefore(opt, this.options[this.options.length - 1]);
                    this.value = val;
                } else {
                    this.value = '';
                }
            }
        });
    }

    if (colSel && colSel.tagName === 'SELECT') {
        colSel.addEventListener('change', function () {
            if (this.value === '__otro_col__') {
                const nuevoCol = prompt('Escribe el color del equipo:');
                if (nuevoCol && nuevoCol.trim()) {
                    const val = nuevoCol.trim();
                    const opt = document.createElement('option');
                    opt.value = val;
                    opt.textContent = val;
                    this.insertBefore(opt, this.options[this.options.length - 1]);
                    this.value = val;
                } else {
                    this.value = '';
                }
            }
        });
    }

    function actualizarModelos(marcaElegida, modeloPre = '', memPre = '', colPre = '') {
        if (!marcaElegida) {
            modeloSel.innerHTML = `<option value="">-- Primero elija Marca --</option>`;
            if (marcaCustom) marcaCustom.classList.add('d-none');
            if (modeloCustom) modeloCustom.classList.add('d-none');
            resetCapacidadYColor();
            return;
        }

        if (marcaElegida === '__otra__') {
            if (marcaCustom) {
                marcaCustom.classList.remove('d-none');
                marcaCustom.focus();
            }
            modeloSel.innerHTML = `<option value="__otro__" selected>✍️ Escribir referencia abajo...</option>`;
            if (modeloCustom) {
                modeloCustom.classList.remove('d-none');
            }
            actualizarEspecificacionesDeReferencia('__otra__', '__otro__', memPre, colPre);
            return;
        }

        if (marcaCustom) marcaCustom.classList.add('d-none');
        const modelosObj = window.CATALOGO_CELULARES[marcaElegida] || {};
        const modelosList = Object.keys(modelosObj);

        let modHtml = `<option value="">-- Seleccione Referencia --</option>`;
        modelosList.forEach(mod => {
            modHtml += `<option value="${mod}">${mod}</option>`;
        });
        if (modeloPre && !modelosList.includes(modeloPre)) {
            modHtml += `<option value="${modeloPre}">${modeloPre}</option>`;
        }
        modHtml += `<option value="__otro__">➕ Agregar otra referencia...</option>`;
        modeloSel.innerHTML = modHtml;

        if (modeloPre) {
            modeloSel.value = modeloPre;
            actualizarEspecificacionesDeReferencia(marcaElegida, modeloPre, memPre, colPre);
        } else {
            resetCapacidadYColor();
        }
        if (modeloCustom) modeloCustom.classList.add('d-none');
    }

    marcaSel.addEventListener('change', function () {
        actualizarModelos(this.value);
        sincronizarInputsOcultos(prefix);
    });

    modeloSel.addEventListener('change', function () {
        if (this.value === '__otro__') {
            if (modeloCustom) {
                modeloCustom.classList.remove('d-none');
                modeloCustom.focus();
            }
            actualizarEspecificacionesDeReferencia(marcaSel.value, '__otro__');
        } else {
            if (modeloCustom) modeloCustom.classList.add('d-none');
            actualizarEspecificacionesDeReferencia(marcaSel.value, this.value);
        }
        sincronizarInputsOcultos(prefix);
    });

    if (marcaCustom) marcaCustom.addEventListener('input', () => sincronizarInputsOcultos(prefix));
    if (modeloCustom) modeloCustom.addEventListener('input', () => sincronizarInputsOcultos(prefix));

    resetCapacidadYColor();
    if (defaults.marca) {
        if (marcasList.includes(defaults.marca)) {
            marcaSel.value = defaults.marca;
            actualizarModelos(defaults.marca, defaults.modelo || '', defaults.memoria || '', defaults.color || '');
        } else {
            marcaSel.value = '__otra__';
            if (marcaCustom) {
                marcaCustom.classList.remove('d-none');
                marcaCustom.value = defaults.marca;
            }
            actualizarModelos('__otra__', '', defaults.memoria || '', defaults.color || '');
            if (modeloCustom && defaults.modelo) {
                modeloCustom.classList.remove('d-none');
                modeloCustom.value = defaults.modelo;
            }
        }
        sincronizarInputsOcultos(prefix);
    }
};

window.obtenerMarcaModeloSelector = function (prefix) {
    const marcaSel = document.getElementById(`${prefix}_marca_select`);
    const marcaCustom = document.getElementById(`${prefix}_marca_custom`);
    const modeloSel = document.getElementById(`${prefix}_modelo_select`);
    const modeloCustom = document.getElementById(`${prefix}_modelo_custom`);
    const memSel = document.getElementById(`${prefix}_memoria_select`);
    const colSel = document.getElementById(`${prefix}_color_select`);

    let marca = '';
    if (marcaSel) {
        marca = (marcaSel.value === '__otra__') ? (marcaCustom ? marcaCustom.value.trim() : '') : marcaSel.value.trim();
    }
    let modelo = '';
    if (modeloSel) {
        modelo = (modeloSel.value === '__otro__') ? (modeloCustom ? modeloCustom.value.trim() : '') : modeloSel.value.trim();
    }
    const memoria = (memSel && memSel.value !== '__otra_cap__') ? memSel.value.trim() : '';
    const color = (colSel && colSel.value !== '__otro_col__') ? colSel.value.trim() : '';

    return { marca, modelo, memoria, color };
};

function sincronizarInputsOcultos(prefix) {
    const { marca, modelo } = window.obtenerMarcaModeloSelector(prefix);
    const hiddenMarca = document.getElementById(`${prefix}_marca_hidden`);
    const hiddenModelo = document.getElementById(`${prefix}_modelo_hidden`);
    if (hiddenMarca) hiddenMarca.value = marca;
    if (hiddenModelo) hiddenModelo.value = modelo;
}
